-- ============================================================
-- 確認用：active_seeds が 30 になっていれば成功。
-- 30 でなければ配布しないこと。
-- ============================================================
select
  count(*) filter (where is_active) as active_seeds,
  count(*)                          as total_seeds
from public.memory_trigger_episodes
where source_type = 'seed';
