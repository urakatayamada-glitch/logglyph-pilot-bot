-- 背景
--
-- Wave 1 は Wave 0 と同じ人に配る。「前にも同じ話を聞かれた」は
-- 一度で意欲を削ぐため、同じ話が回ってこない状態を作る必要がある。
--
-- 根本原因はコード側にあり、別途修正した：
--   app/page.tsx が pickEpisode() を除外リスト無しで呼んでいたため、
--   直近に出したEpisodeの記録は取っていたのに、初回表示では
--   一切使われていなかった。重複は運任せだった。
--   → Cookie 経由でサーバー側にも渡すよう修正済み。
--   → RECENT_EPISODE_MEMORY も 8 → 20 へ。
--
-- そのうえで、母数そのものを増やす。
--   1. Wave 0 で 0006 が無効化した10件を戻す（10 → 20）
--   2. 新しい10件を追加する（20 → 30）
--
-- トレードオフ：Episode 1件あたりの露出回数は下がる。
-- Wave 1 は Episode 別成績よりも継続意向を見る Package Test なので、
-- 変化に気づかれないことより飽きられないことを優先する。
--
-- ------------------------------------------------------------
-- 新規10件の設計
--
-- Wave 0 で実際に記憶が出た領域から素材を取った。
-- 結びは全て「具体的な出来事の型 + ある？」に揃えている
-- （「覚えてる？」と記憶の有無を聞く形は Wave 0 で 0% だった）。
-- 語りは全て伝聞型。秘密の直接要求は含まない。
-- ============================================================

