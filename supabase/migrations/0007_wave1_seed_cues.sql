-- ============================================================
-- LOGGLYPH Pilot Wave 1 : Episode の問いかけ（Cue）差し替え
--
-- 変更日   : 2026-09-01
-- 対象     : S10 (failure) / S18 (school)
-- バージョン: v1.5.0 / Wave 1
-- 承認     : Product Owner（Wave 1 Product Decision ①）
--
-- ------------------------------------------------------------
-- 差し替える理由（Wave 0 実測）
--
--   failure  8セッション → Memory Found  0%
--   school   9セッション → Memory Found 11%（1件）
--
--   この2本だけで Wave 0 の約38%のセッションを消費して、収穫は1件だった。
--
--   原因は結びが「記憶の有無そのもの」を聞いていること。
--   「覚えてる？」は Yes / No で閉じられる問いで、既定の答えが No になる。
--   実際に返ってきた one_line_memory：
--     「うまくいかなかった日のことは覚えていない。」
--     「特に覚えていることはない。」
--     「何もしてないのに覚えてる日はないかもしれない。」
--
--   一方 Memory Found 100% だった dream の結びは
--     「ずっと言い続けてること、何かある？」
--   で、記憶の有無ではなく「具体的な出来事の型」を聞いている。
--   work（67%）も「怒られるより効いたことってある？」で同じ構造。
--
--   そこで2本とも [具体的な出来事の型] + ある？ の形に揃える。
--
-- decision（3件 0%）と aging（4件 25%）も低いが、n が 3 と 4 では
-- 偶然と区別できないため今回は据え置き、Wave 1 終了後に再評価する。
-- ------------------------------------------------------------

-- ============================================================
-- S10 failure
--
-- 本文（変更なし）:
--   前に聞いた話でさ。
--   面接で落ちたのに、その帰りに食べたラーメンがやたら美味かったのだけ覚えてる人がいて。
--   落ちたこと自体はもう何も感じないらしい。
--
-- 旧Cue: うまくいかなかった日のこと、何か覚えてる？
-- 新Cue: うまくいかなかった日の、全然関係ないところだけ残ってるって、ある？
--
-- 意図: 探す対象を「うまくいかなかった日の記憶」（広く、重い）から
--       「関係ないディテールだけが残っている現象」（狭く、軽い）へ移す。
--       本文のラーメンと同じ型を探せばよくなる。
-- ============================================================
update public.memory_trigger_episodes
set body = replace(
      body,
      'うまくいかなかった日のこと、何か覚えてる？',
      'うまくいかなかった日の、全然関係ないところだけ残ってるって、ある？'
    ),
    note = 'v1.5.0 / 2026-09-01 Cue更新。旧: うまくいかなかった日のこと、何か覚えてる？（Wave 0: 8セッション / Memory Found 0%）'
where body like '%うまくいかなかった日のこと、何か覚えてる？%';

-- ============================================================
-- S18 school
--
-- 本文（変更なし）:
--   前に聞いた話なんだけど。
--   学生のとき、一度だけ授業を抜け出して海を見に行った人がいて。
--   特に何もせず座って帰っただけなのに、その日のことだけ鮮明らしい。
--
-- 旧Cue: 何もしてないのに覚えてる日って、ある？
-- 新Cue: 授業や仕事を、ちょっと抜け出したことって、ある？
--
-- 意図: 旧Cueは「出来事が無いこと」を手がかりに探せと言っており、
--       探索の起点そのものが存在しなかった。
--       本文の核である「そこから抜け出した」という行為を起点にする。
--       「ちょっと」を入れて、離職や逃避のような重い話ではなく
--       本文どおりの小さな逸脱に寄せる。学生にも社会人にも当たる。
-- ============================================================
update public.memory_trigger_episodes
set body = replace(
      body,
      '何もしてないのに覚えてる日って、ある？',
      '授業や仕事を、ちょっと抜け出したことって、ある？'
    ),
    note = 'v1.5.0 / 2026-09-01 Cue更新。旧: 何もしてないのに覚えてる日って、ある？（Wave 0: 9セッション / Memory Found 11%）'
where body like '%何もしてないのに覚えてる日って、ある？%';

-- ============================================================
-- 確認用：2 と出れば成功。2 でなければ配布しないこと。
-- ============================================================
select count(*) as updated_cues
from public.memory_trigger_episodes
where body like '%全然関係ないところだけ残ってるって、ある？%'
   or body like '%ちょっと抜け出したことって、ある？%';

