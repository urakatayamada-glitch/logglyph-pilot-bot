--
-- ⚠ 承認は2段に分けてある。
--    このファイルを実行すると approved = false で入る（画面には出ない）。
--    文面を読んで、直したいところを直したうえで、
--    最後の UPDATE を別に実行して初めて表示される。
--
--    投入と公開を1回のRunで済ませると、文面を読まずに公開できてしまう。
--
-- 表現ルール（Wave 2 設計合意 §5 / Product Decision）
--    禁止  「あなたは○○な人です」
--    禁止  「あなたは失敗から学ぶタイプです」
--    禁止  人格・性格の断定
--    可    「今回話してくれた記憶には、○○という場面がいくつかありました。」
--    可    「もしかすると、○○より○○の方が記憶に残るのかもしれません。」
--    = 本人の発言から観察できる事実 ＋ 断定しない小さな仮説
--
--    会話エンジンの base.ts に入れた境界ルールと同じ原則。
--    主語が自分（受け取る側）の観察にあるかどうかで判断する。
--
-- session_id は直接書かない。one_line_memory で引き当てる。
-- 同じ文が複数あることは無いが、念のため1件に絞っている。
-- ============================================================

insert into public.found_notes (session_id, note, approved)
select s.session_id, v.note, false
from (values
  (
    'SNSでフォローしているが、メッセージは3、4年前で止まっている同級生がいる。',
    'つながりが切れたという話ではなく、つながったまま言葉だけが止まっている、という形で残っていました。もしかすると、連絡が途絶えたことより、途絶えたまま見えていることの方が残るのかもしれません。'
  ),
  (
    '学生時代、一緒に昼休みを過ごしたり喧嘩した友達がいたが、実は嫌いだった。',
    '一緒にいた時間と、そのとき思っていたことが、同じ記憶の中に並んで残っていました。片方だけを覚えている、という形ではありませんでした。'
  ),
  (
    '県内のいろんなところをドライブして、カフェやハンバーガー屋に行った。',
    'どこに着いたかより、あちこち回ったこと自体が残っていました。もしかすると、決めて向かった場所より、その日たまたま寄った場所の方が覚えているのかもしれません。'
  ),
  (
    '初めてのバイト代でモンキーという50ccのギア車を買い、福岡の専門学校時代に通勤で使用していたが、最後は盗まれた。',
    '「買ったこと」より「盗まれたこと」の方が、車種も場所も残った形で覚えられていました。'
  ),
  (
    '同じ日に二つの誘いが重なった時、どっちも行くこともあるし、どっちも楽しかった。',
    'どちらかを選んだ話ではなく、両方行った話として残っていました。もしかすると、選ばなかった方より、選ばずに済んだことの方が覚えているのかもしれません。'
  ),
  (
    '友達と名古屋の栄や錦で遊び、友達の分を立て替えて楽しく過ごした。',
    '立て替えたことが、損得の話ではなく、楽しかった日の一部として残っていました。'
  )
) as v(memory, note)
join lateral (
  select session_id
  from public.sessions
  where one_line_memory = v.memory
    and content_deleted_at is null
  order by started_at
  limit 1
) s on true
on conflict (session_id) do update
  set note = excluded.note,
      updated_at = now();
      -- approved は上書きしない。承認済みを未承認へ戻さないため。

