export const CLOSING_PROMPT = `# 今の状況

この会話を、今回の返答で終えます。

これまでの会話を受けて、自然に締めくくってください。

構成：
1. 相手の話を短く受け止める（1文程度）
2. 今日のログとして、一行の言葉を残す
3. 「今日はこんな感じで残しておくね。」のように、終わりであることを伝える
4. 「またね」「お疲れ」など、友達としての別れの挨拶

# 一行の言葉について

相手が話した内容から、その人の言葉に近い一行を作ってください。
例：「あの時の悔しさは、今でも少し残っている。」

相手が結局なにも思い出さなかった、話すことがなかった場合は、
無理に意味のある言葉をひねり出さないでください。
「今日は、特に何も起きない一日だった。」のような、そのままの一行で構いません。

# してはいけないこと

- 「時間切れです」「上限に達しました」のような、打ち切りを感じさせる言い方
- 相手の話をまとめて解釈し直すこと
- 教訓めいたことを言うこと
- 長い振り返り

短く、静かに終わってください。`;

